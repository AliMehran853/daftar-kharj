export const TIME_RANGE_LABELS = {
  sahar: 'سحر',
  sobh: 'صبح',
  chasht: 'چاشت',
  'bad-az-zohr': 'بعد از ظهر',
  sham: 'شام',
  shab: 'شب',
}

export function getCurrentTimeRange(date = new Date()) {
  const h = date.getHours()
  if (h >= 4 && h < 6) return 'sahar'
  if (h >= 6 && h < 11) return 'sobh'
  if (h >= 11 && h < 14) return 'chasht'
  if (h >= 14 && h < 17) return 'bad-az-zohr'
  if (h >= 17 && h < 20) return 'sham'
  return 'shab'
}